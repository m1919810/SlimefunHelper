package xyz.wagyourtail.jsmacros.client.api.classes.math;

public class Pos2D {
    public double x;
    public double y;

    public Pos2D(double x, double y) {
        this.x = x;
        this.y = y;
    }

    public double getX() {
        return x;
    }

    public double getY() {
        return y;
    }
}
